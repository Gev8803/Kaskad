class Command(BaseCommand):
    help = "Import/refresh the full KD-2 module family from the source catalogue."

    def add_arguments(self, parser):
        parser.add_argument("--no-assets", action="store_true",
                            help="Skip image/PDF attachment (metadata only).")

    @transaction.atomic
    def handle(self, *args, **opts):
        cat = models.SwitchgearCategory.objects.filter(slug="kd-2").first()
        if not cat:
            self.stderr.write("KD-2 category (slug='kd-2') not found. Run seed_content first.")
            return
        # wipe existing items (cascades to gallery/bullets/spec rows)
        n = cat.items.count()
        cat.items.all().delete()
        self.stdout.write(f"Removed {n} existing KD-2 items.")

        for i, m in enumerate(MODULES):
            it = models.SwitchgearItem(
                category=cat, code=m["code"], sort=i, is_published=True,
                name_hy=m["title"]["hy"], name_ru=m["title"]["ru"], name_en=m["title"]["en"],
                description_hy=m["desc"]["hy"], description_ru=m["desc"]["ru"], description_en=m["desc"]["en"],
                purpose_hy=m["purpose"]["hy"], purpose_ru=m["purpose"]["ru"], purpose_en=m["purpose"]["en"],
                spec_cols=m["cols"],
                notes_hy=m["notes"].get("hy", ""), notes_ru=m["notes"].get("ru", ""),
                notes_en=m["notes"].get("en", ""),
            )
            if m.get("fuse"):
                import json
                it.fuse_table = json.dumps(m["fuse"], ensure_ascii=False)
            if not opts["no_assets"]:
                cover = os.path.join(ASSET_DIR, f"{m['assets']}_0.jpg")
                if os.path.exists(cover):
                    with open(cover, "rb") as fh:
                        it.image.save(f"{m['assets']}.jpg", File(fh), save=False)
                if m["pdf"]:
                    pdf = os.path.join(ASSET_DIR, f"{m['assets']}.pdf")
                    if os.path.exists(pdf):
                        with open(pdf, "rb") as fh:
                            it.pdf.save(f"{m['code']}.pdf", File(fh), save=False)
            it.save()

            # spec rows
            for j, s in enumerate(m["specs"]):
                models.SwitchgearItemSpecRow.objects.create(
                    item=it, sort=j, is_group=s["group"],
                    param_hy=s["param"]["hy"], param_ru=s["param"]["ru"], param_en=s["param"]["en"],
                    unit=s["unit"]["en"],
                    v1=s["v"][0], v2=s["v"][1], v3=s["v"][2],
                )
            # bullets
            order = 0
            for kind, key in (("equipment", "equipment"), ("option", "options"), ("vacuum", "vacuum")):
                for phrase in m.get(key, []):
                    b = ph(phrase)
                    models.SwitchgearItemBullet.objects.create(
                        item=it, kind=kind, sort=order,
                        text_hy=b["hy"], text_ru=b["ru"], text_en=b["en"],
                    )
                    order += 1
            # gallery
            if not opts["no_assets"]:
                for gi, idx in enumerate(m["gallery"]):
                    gp = os.path.join(ASSET_DIR, f"{m['assets']}_{idx}.jpg")
                    if os.path.exists(gp):
                        img = models.SwitchgearItemImage(item=it, sort=gi, alt=m["code"])
                        with open(gp, "rb") as fh:
                            img.image.save(f"{m['assets']}_{idx}.jpg", File(fh), save=False)
                        img.save()
            self.stdout.write(f"  + {m['code']} ({len(m['specs'])} specs, "
                              f"{len(m.get('equipment', []))}+{len(m.get('options', []))}+"
                              f"{len(m.get('vacuum', []))} bullets)")

        self.stdout.write(self.style.SUCCESS(f"Imported {len(MODULES)} KD-2 modules."))
